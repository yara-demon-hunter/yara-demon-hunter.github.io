#!/usr/bin/env ruby
# Copia a biblioteca de personagens, monstros e cenários (mini_games/_library) para dentro de cada jogo ligado em sync.json.
# Cada jogo continua independente: ele importa só a própria cópia (ex.: last_torch/library), nunca esta pasta.
#
#   ruby mini_games/_library/sync.rb               copia para todos os jogos com "enabled": true
#   ruby mini_games/_library/sync.rb last_torch    copia só para este jogo (precisa estar ligado)
#   ruby mini_games/_library/sync.rb --check       só confere: sai com erro se alguma cópia estiver diferente
#
# A cópia é um espelho: arquivo apagado ou renomeado aqui some lá também. Ficam de fora a arte de referência
# (art_reference/), as ferramentas (tools/), os .md e os arquivos do próprio sync. Na cópia são gerados README.md, CLAUDE.md e AGENTS.md
# avisando para não editar lá, e cada .js copiado ganha na primeira linha um comentário apontando para o original.

require "digest"
require "fileutils"
require "json"
require "pathname"

LIBRARY = Pathname(__dir__).expand_path
GAMES_ROOT = LIBRARY.parent
MARKER = ".synced-from-library"
COPY_README = <<~TEXT
  # Cópia da biblioteca de personagens, monstros e cenários

  **Não edite nada nesta pasta.** Ela é gerada a partir de `mini_games/_library/` e é apagada e refeita a cada sync.

  Para mudar um personagem, monstro ou cenário, edite em `mini_games/_library/` e rode, na raiz do repositório:

  ```bash
  ruby mini_games/_library/sync.rb
  ```

  O que é cada pasta, como ligar a biblioteca em outro jogo e como criar um personagem novo: `mini_games/_library/README.md`.
TEXT
AGENT_NOTE = <<~TEXT
  # Instruções para IAs e agentes de código

  Esta pasta (`library/`) é uma **cópia gerada**. **Nunca edite, crie ou apague arquivos aqui**: o próximo sync
  desfaz tudo e `sync.rb --check` acusa a diferença.

  Para qualquer mudança de arte de personagem, monstro ou cenário (desenho, cores, medidas, animação):

  1. Edite o arquivo de mesmo caminho em `mini_games/_library/` (ex.: `library/monsters/topdown/bat/bat.js` →
     `mini_games/_library/monsters/topdown/bat/bat.js`). A primeira linha de cada `.js` daqui diz qual é o original.
  2. Rode na raiz do repositório: `ruby mini_games/_library/sync.rb`
  3. Confira: `ruby mini_games/_library/sync.rb --check`

  Regras do jogo e balanceamento (vida, dano, ataques) não ficam aqui: ficam no código do próprio jogo.
  Manual completo: `mini_games/_library/README.md`. Referência de arte: `mini_games/_library/<tipo>/<id>/art_reference/` (cenários: `scenery/<id>/art_reference/`).
TEXT

def banner(rel)
  "// GERADO por mini_games/_library/sync.rb. NÃO EDITE: altere mini_games/_library/#{rel} e rode o sync.\n"
end

def library_files
  LIBRARY.glob("**/*", File::FNM_DOTMATCH).select(&:file?).map { |path| path.relative_path_from(LIBRARY) }.reject do |rel|
    parts = rel.each_filename.to_a
    parts.include?("art_reference") || parts.first == "tools" || parts.any? { |part| part.start_with?(".") } ||
      rel.extname == ".md" || %w[sync.rb sync.json].include?(rel.to_s)
  end.sort
end

# O que a cópia deve conter: { caminho relativo => conteúdo }
def expected_copy
  files = library_files.to_h do |rel|
    content = LIBRARY.join(rel).binread
    content = banner(rel).b + content if rel.extname == ".js"
    [rel.to_s, content]
  end
  files["README.md"] = COPY_README
  files["CLAUDE.md"] = AGENT_NOTE
  files["AGENTS.md"] = AGENT_NOTE
  files[MARKER] = "Generated by mini_games/_library/sync.rb\n"
  files
end

def current_copy(target)
  return {} unless target.directory?
  target.glob("**/*", File::FNM_DOTMATCH).select(&:file?).to_h { |path| [path.relative_path_from(target).to_s, path.binread] }
end

def differences(target)
  want = expected_copy
  have = current_copy(target)
  changed = want.keys.select { |rel| have.key?(rel) && Digest::SHA256.digest(have[rel]) != Digest::SHA256.digest(want[rel]) }
  { missing: want.keys - have.keys, extra: have.keys - want.keys, changed: changed }
end

def sync(name, target)
  if target.exist? && !target.join(MARKER).file?
    abort "#{name}: #{target} já existe e não foi criado por este sync. Apague ou renomeie a pasta antes."
  end
  diff = differences(target)
  want = expected_copy
  (diff[:missing] + diff[:changed]).each do |rel|
    FileUtils.mkdir_p(target.join(rel).dirname)
    target.join(rel).binwrite(want[rel])
  end
  diff[:extra].each { |rel| FileUtils.rm_f(target.join(rel)) }
  # Pastas que ficaram vazias (personagem apagado ou renomeado)
  target.glob("**/").sort_by { |dir| -dir.to_s.length }.each { |dir| dir.rmdir if dir != target && dir.empty? }
  total = diff.values.sum(&:length)
  puts "#{name}: #{total.zero? ? 'já estava igual' : "#{diff[:missing].length} novos, #{diff[:changed].length} atualizados, #{diff[:extra].length} removidos"} (#{target.relative_path_from(GAMES_ROOT.parent)})"
end

config = JSON.parse(LIBRARY.join("sync.json").read)
games = config.fetch("games")
check = ARGV.delete("--check")
wanted = ARGV.empty? ? games.select { |_, game| game["enabled"] }.keys : ARGV

failed = false
wanted.each do |name|
  game = games[name] or abort "#{name}: não está em sync.json"
  abort "#{name}: está desligado em sync.json (\"enabled\": false). #{game['note']}".strip unless game["enabled"]
  target = GAMES_ROOT.join(game.fetch("target"))
  if check
    diff = differences(target)
    if diff.values.all?(&:empty?)
      puts "#{name}: igual à biblioteca"
    else
      failed = true
      puts "#{name}: DIFERENTE da biblioteca (rode o sync sem --check)"
      diff.each { |kind, list| list.each { |rel| puts "  #{kind}: #{rel}" } }
    end
  else
    sync(name, target)
  end
end
exit(1) if failed
