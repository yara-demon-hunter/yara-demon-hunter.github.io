#!/usr/bin/env ruby
# Build a standalone game folder from the same Jekyll-rendered game source
# used by the website. No game code is duplicated in the output folder.

require "fileutils"
require "pathname"

repo_root = Pathname(__dir__).join("../..").expand_path
source_game = Pathname(__dir__).expand_path
site_output = repo_root.join("_site/mini_games/yara-rpg/standalone.html")
build_output = source_game.join("standalone-build")

unless site_output.file?
  abort "Missing #{site_output}. Run `bundle exec jekyll build` first."
end

unless source_game.join("css/tailwind.css").file?
  abort "Missing css/tailwind.css. Run mini_games/yara-rpg/build-tailwind.sh first."
end

marker = build_output.join(".generated-by-yara-rpg-build")
if build_output.exist? && !marker.file?
  abort "Refusing to overwrite #{build_output}: it is not marked as generated output."
end

FileUtils.rm_rf(build_output) if build_output.exist?
FileUtils.mkdir_p(build_output)
FileUtils.cp(site_output, build_output.join("index.html"))

%w[js css images audio scenes].each do |directory|
  FileUtils.cp_r(source_game.join(directory), build_output.join(directory))
end

# Keep documentation and site-only styles out of the upload package.
Dir.glob(build_output.join("**/*.md")).each { |path| FileUtils.rm_f(path) }
%w[css/game.css css/embedded-rpg.css images/cover.webp scenes/preview.html].each do |path|
  FileUtils.rm_f(build_output.join(path))
end

File.write(marker, "Generated by mini_games/yara-rpg/build-standalone.rb\n")

files = Dir.glob(build_output.join("**/*"), File::FNM_DOTMATCH).select { |path| File.file?(path) }
bytes = files.sum { |path| File.size(path) }
puts "Standalone game package created: #{build_output}"
puts "#{files.length - 1} files, #{format('%.2f', bytes / 1_048_576.0)} MiB"
puts "Upload the contents of this folder; index.html is the entry point."
